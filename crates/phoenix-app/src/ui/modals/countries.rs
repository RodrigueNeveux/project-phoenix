#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Country {
    pub alpha2: &'static str,
    pub code: &'static str,
    pub en: &'static str,
    pub fr: &'static str,
}

impl Country {
    pub fn name(&self) -> &'static str {
        if crate::i18n::locale().starts_with("fr") { self.fr } else { self.en }
    }
}

const fn ct(alpha2: &'static str, code: &'static str, en: &'static str, fr: &'static str) -> Country {
    Country { alpha2, code, en, fr }
}

